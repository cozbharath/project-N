package com.abstract1;

public class Lion implements Animal {

	@Override
	public void sound() {
		System.out.println("Lions Roar");

	}

	@Override
	public void walk() {
		System.out.println("Lions Walk with Attitude");

	}

	@Override
	public void sleep() {
		System.out.println("Lions only sleep when they are full");

	}

	@Override
	public void eat() {
		System.out.println("Lions love to eat the fresh meat");

	}

	@Override
	public void drink() {
		System.out.println("Lions Drink Blood");

	}

	@Override
	public void play() {
		System.out.println("Lions play with their Childrens");

	}

	@Override
	public void jump() {
		System.out.println("Lions cant jump");

	}

	@Override
	public void hunt() {
		System.out.println("Lions can hunt any animal");

	}

	@Override
	public void swim() {
		System.out.println("Lions love to swin in cold water");

	}

	@Override
	public void run() {
		System.out.println("Lions run Faster");

	}

}
